import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import test from 'node:test';

import {
  buildDependencyInventory,
  inventoryAssetName,
  parseCargoLock,
  parseEngineLock
} from './release-dependency-inventory.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (relativePath) => readFileSync(path.join(repoRoot, relativePath), 'utf8');
const COMMIT = 'a'.repeat(40);
const EPOCH = 1_786_939_861;
const REGISTRY = 'registry+https://github.com/rust-lang/crates.io-index';
const CHECKSUM = 'c'.repeat(64);

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "coven-cli"
version = "0.0.0"
dependencies = [
 "serde",
 "threads 0.2.0",
]

[[package]]
name = "serde"
version = "1.0.228"
source = "${REGISTRY}"
checksum = "${CHECKSUM}"

[[package]]
name = "threads"
version = "0.2.0"
source = "git+https://github.com/OpenCoven/coven-threads?rev=${'b'.repeat(40)}#${'b'.repeat(40)}"
dependencies = []
`;

const ENGINE = `version = "0.8.0"
contract = 1

[sha256]
"coven-code-linux-x86_64.tar.gz" = "${'d'.repeat(64)}"
"coven-code-macos-aarch64.tar.gz" = "${'e'.repeat(64)}"
`;

function inventory(overrides = {}) {
  return buildDependencyInventory({
    releaseTag: 'v0.4.11',
    npmVersion: '0.4.11',
    sourceCommit: COMMIT,
    sourceDateEpoch: EPOCH,
    cargoLock: LOCK,
    engineLock: ENGINE,
    actionsLock: { actions: { 'actions/checkout': { sha: '3'.repeat(40), ref: 'v7.0.1', refKind: 'tag' } } },
    rustToolchain: '1.99.1',
    nodeVersion: '24.22.0',
    ...overrides
  });
}

test('lockfile packages become components with provenance for each source kind', () => {
  const bom = inventory();
  assert.equal(bom.bomFormat, 'CycloneDX');
  assert.equal(bom.specVersion, '1.5');
  const byName = Object.fromEntries(bom.components.map((component) => [component.name, component]));
  assert.deepEqual(byName.serde.hashes, [{ alg: 'SHA-256', content: CHECKSUM }]);
  assert.equal(byName.serde.purl, 'pkg:cargo/serde@1.0.228');
  assert.deepEqual(byName.threads.externalReferences, [
    { type: 'vcs', url: `https://github.com/OpenCoven/coven-threads#${'b'.repeat(40)}` }
  ]);
  assert.equal(
    byName.threads.purl,
    `pkg:cargo/threads@0.2.0?vcs_url=${encodeURIComponent(`git+https://github.com/OpenCoven/coven-threads@${'b'.repeat(40)}`)}`
  );
  assert.deepEqual(byName['coven-cli'].properties, [{ name: 'coven:workspace-member', value: 'true' }]);
  assert.equal(byName['coven-code'].scope, 'optional');
  assert.deepEqual(byName['coven-code'].properties.map((entry) => entry.name), [
    'coven:engine-asset-sha256:coven-code-linux-x86_64.tar.gz',
    'coven:engine-asset-sha256:coven-code-macos-aarch64.tar.gz'
  ]);
  assert.equal(byName['@opencoven/cli-windows'].purl, 'pkg:npm/%40opencoven/cli-windows@0.4.11');
  assert.equal(byName['actions/checkout'].scope, 'excluded');
  assert.equal(byName['actions/checkout'].purl, `pkg:githubactions/actions/checkout@${'3'.repeat(40)}`);
});

test('the dependency graph resolves every lockfile reference', () => {
  const { dependencies } = inventory();
  const cli = dependencies.find((entry) => entry.ref === 'pkg:cargo/coven-cli@0.0.0');
  assert.deepEqual(cli.dependsOn, [
    'pkg:cargo/serde@1.0.228',
    `pkg:cargo/threads@0.2.0?vcs_url=${encodeURIComponent(`git+https://github.com/OpenCoven/coven-threads@${'b'.repeat(40)}`)}`
  ]);
});

test('metadata binds the release, the source, the toolchains, and the scope caveat', () => {
  const { metadata, serialNumber } = inventory();
  assert.equal(metadata.timestamp, '2026-08-17T04:11:01Z');
  assert.equal(metadata.component.purl, 'pkg:npm/%40opencoven/cli@0.4.11');
  assert.deepEqual(metadata.component.externalReferences, [{ type: 'vcs', url: `git+https://github.com/OpenCoven/coven#${COMMIT}` }]);
  const properties = Object.fromEntries(metadata.properties.map((entry) => [entry.name, entry.value]));
  assert.equal(properties['coven:source-commit'], COMMIT);
  assert.equal(properties['coven:rust-toolchain'], '1.99.1');
  assert.equal(properties['coven:node'], '24.22.0');
  assert.match(properties['coven:inventory-scope'], /superset of what each native binary links/);
  assert.match(serialNumber, /^urn:uuid:[0-9a-f]{8}-[0-9a-f]{4}-5[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
});

test('the same source produces the same bytes, and another commit another serial', () => {
  assert.equal(JSON.stringify(inventory()), JSON.stringify(inventory()));
  assert.notEqual(inventory().serialNumber, inventory({ sourceCommit: 'f'.repeat(40) }).serialNumber);
});

test('refuses lockfile packages it cannot account for', () => {
  const cases = [
    [LOCK.replace(`checksum = "${CHECKSUM}"\n`, ''), /serde 1\.0\.228 has no sha256 checksum/],
    [LOCK.replace(`#${'b'.repeat(40)}"`, '"'), /unsupported source/],
    [LOCK.replace('source = "registry+https://github.com/rust-lang/crates.io-index"', 'source = "sparse+https://example.test/index/"'), /unsupported source/],
    [LOCK.replace(' "serde",\n', ' "missing",\n'), /"missing" of coven-cli resolves to 0 packages/],
    [`${LOCK}\n[[package]]\nname = "serde"\nversion = "2.0.0"\nsource = "${REGISTRY}"\nchecksum = "${CHECKSUM}"\n`, /"serde" of coven-cli resolves to 2 packages/],
    [`${LOCK}\n[[package]]\nname = "serde"\nversion = "1.0.228"\nsource = "${REGISTRY}"\nchecksum = "${CHECKSUM}"\n`, /two components named pkg:cargo\/serde@1\.0\.228/],
    [LOCK.replace('version = "0.0.0"\n', ''), /without a name and version/],
    [LOCK.replace('name = "serde"', 'name = serde'), /expected a quoted string/]
  ];
  for (const [cargoLock, expected] of cases) {
    assert.throws(() => inventory({ cargoLock }), expected);
  }
});

test('refuses an engine lock or source identity it cannot bind', () => {
  assert.throws(() => inventory({ engineLock: 'version = "0.8.0"\n' }), /at least one sha256 asset digest/);
  assert.throws(() => inventory({ sourceCommit: 'main' }), /40-character SHA/);
  assert.throws(() => inventory({ sourceDateEpoch: -1 }), /non-negative integer/);
});

test('the real lockfile and engine pin produce a complete inventory', () => {
  const lock = read('Cargo.lock');
  const packages = parseCargoLock(lock);
  assert.equal(packages.length, (lock.match(/^\[\[package\]\]$/gm) ?? []).length);
  const engine = parseEngineLock(read('crates/coven-cli/engine.lock'));
  assert.ok(Object.keys(engine.assets).length >= 4);
  const bom = inventory({
    cargoLock: lock,
    engineLock: read('crates/coven-cli/engine.lock'),
    actionsLock: JSON.parse(read('.github/actions-lock.json'))
  });
  const crates = bom.components.filter((component) => component.purl.startsWith('pkg:cargo/'));
  assert.equal(crates.length, packages.length);
  assert.ok(crates.every((component) => component.hashes || component.externalReferences || component.properties));
  assert.equal(bom.dependencies.length, packages.length);
  assert.equal(inventoryAssetName('0.4.11'), 'coven-v0.4.11-sbom.cdx.json');
});
